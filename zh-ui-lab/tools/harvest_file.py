def main():
    unc = json.load(io.open(os.path.join(LAB, r"dash\uncovered-files.json"), encoding="utf-8"))
    texts = sorted(
        {e["text"] for e in unc if any(FRAG in f for f in e["files"])},
        key=lambda s: (len(s.split()), s),
    )
    if len(texts) != len(ZH):
        print("候选数量变了:", len(texts), "译文条数:", len(ZH))
        return 1
    out = {}
    for t, zh in zip(texts, ZH):
        if zh is None:
            continue
        out[t] = zh
    json.dump(out, io.open(os.path.join(LAB, OUT), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("落词典:", len(out), "/", len(texts))
    for t in texts[:3]:
        print("  样例:", repr(t[:52]), "->", repr(out.get(t)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
